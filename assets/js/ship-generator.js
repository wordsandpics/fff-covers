(function () {
  'use strict';

  const STORAGE_KEY = 'fff-covers-ship-generator-v1';
  const GENERATOR_MARKER = '# Generated by the fff-covers short ship generator v4';
  const DEFAULT_LIMIT = 2;
  const CALIBRE_TEMPLATE_LIMIT = 32767;
  window.FFFShipGeneratorCore = {
    generateTemplate: generateTemplate,
    parseTemplate: parseTemplate,
    previewValue: previewValue,
    regexEscape: regexEscape
  };

  const root = document.getElementById('ship-generator');
  if (!root) return;

  const examples = [
    {
      pairing: 'Sherlock Holmes/John Watson',
      shortName: 'Johnlock',
      aliases: ['John/Sherlock', 'Sherlock/John']
    },
    {
      pairing: 'Shane Hollander/Ilya Rozanov',
      shortName: 'Hollanov',
      aliases: []
    }
  ];

  const elements = {
    mappingList: document.getElementById('mapping-list'),
    shipLimit: document.getElementById('ship-limit'),
    categoryFallback: document.getElementById('category-fallback'),
    categoryFallbackSettings: document.getElementById('category-fallback-settings'),
    categoryColumn: document.getElementById('category-column'),
    addMapping: document.getElementById('add-mapping'),
    clearMappings: document.getElementById('clear-mappings'),
    loadExamples: document.getElementById('load-examples'),
    importCode: document.getElementById('import-code'),
    importTemplate: document.getElementById('import-template'),
    clearImport: document.getElementById('clear-import'),
    importMessage: document.getElementById('import-message'),
    validationMessage: document.getElementById('validation-message'),
    previewInput: document.getElementById('preview-input'),
    previewCategoryWrap: document.getElementById('preview-category-wrap'),
    previewCategory: document.getElementById('preview-category'),
    previewOutput: document.getElementById('preview-output'),
    generateTemplate: document.getElementById('generate-template'),
    outputWrap: document.getElementById('generator-output-wrap'),
    generatedCode: document.getElementById('generated-code'),
    copyTemplate: document.getElementById('copy-template'),
    downloadTemplate: document.getElementById('download-template'),
    copyMessage: document.getElementById('copy-message')
  };

  const draft = loadDraft();
  let mappings = draft.mappings;
  let nextId = mappings.reduce((largest, item) => Math.max(largest, item.id || 0), 0) + 1;

  if (!mappings.length) mappings = [newMapping()];
  elements.categoryFallback.checked = draft.categoryFallback;
  elements.categoryColumn.value = draft.categoryColumn;
  syncCategoryControls();
  renderMappings();
  updatePreview();

  elements.addMapping.addEventListener('click', function () {
    mappings.push(newMapping());
    renderMappings();
    focusMapping(mappings[mappings.length - 1].id);
    changed();
  });

  elements.clearMappings.addEventListener('click', function () {
    if (mappings.some(hasContent) && !window.confirm('Clear every ship row?')) return;
    mappings = [newMapping()];
    renderMappings();
    changed();
  });

  elements.loadExamples.addEventListener('click', function () {
    if (mappings.some(hasContent) && !window.confirm('Replace your current rows with the tutorial examples?')) return;
    mappings = examples.map(function (item) {
      return Object.assign({ id: nextId++ }, item, { aliases: item.aliases.slice() });
    });
    elements.shipLimit.value = String(DEFAULT_LIMIT);
    elements.previewInput.value = 'Sherlock Holmes/John Watson, Sherlock Holmes/John Watson, Shane Hollander/Ilya Rozanov';
    renderMappings();
    changed();
  });

  elements.shipLimit.addEventListener('change', changed);
  elements.previewInput.addEventListener('input', updatePreview);
  elements.previewCategory.addEventListener('input', updatePreview);
  elements.categoryFallback.addEventListener('change', function () {
    syncCategoryControls();
    changed();
  });
  elements.categoryColumn.addEventListener('input', changed);

  elements.clearImport.addEventListener('click', function () {
    elements.importCode.value = '';
    showMessage(elements.importMessage, '', 'info');
  });

  elements.importTemplate.addEventListener('click', importTemplate);
  elements.generateTemplate.addEventListener('click', function () {
    syncMappingsFromForm();
    const validation = validateMappings();
    showValidation(validation);
    if (validation.errors.length) {
      showMessage(elements.copyMessage, 'Fix the highlighted problems before generating the template.', 'error');
      return;
    }
    const generated = generateTemplate(cleanMappings(), Number(elements.shipLimit.value), {
      categoryFallback: elements.categoryFallback.checked,
      categoryColumn: elements.categoryColumn.value
    });
    elements.generatedCode.value = generated;
    elements.outputWrap.hidden = false;
    const tooLong = generated.length > CALIBRE_TEMPLATE_LIMIT;
    elements.copyTemplate.disabled = tooLong;
    elements.downloadTemplate.disabled = tooLong;
    showMessage(
      elements.copyMessage,
      tooLong
        ? 'This template is longer than Calibre can save. Remove some mappings and generate it again.'
        : 'Template generated. Copy it into your #short_ships column.',
      tooLong ? 'error' : 'success'
    );
    saveDraft();
  });

  elements.copyTemplate.addEventListener('click', async function () {
    try {
      await navigator.clipboard.writeText(elements.generatedCode.value);
      showMessage(elements.copyMessage, 'Copied. You can now paste the template into Calibre.', 'success');
    } catch (error) {
      elements.generatedCode.focus();
      elements.generatedCode.select();
      showMessage(elements.copyMessage, 'The browser could not copy automatically. The code is selected; use your normal copy command.', 'error');
    }
  });

  elements.downloadTemplate.addEventListener('click', function () {
    const blob = new Blob([elements.generatedCode.value], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = 'short_ships.txt';
    document.body.appendChild(link);
    link.click();
    link.remove();
    URL.revokeObjectURL(url);
  });

  function newMapping(values) {
    return Object.assign({ id: nextId++, pairing: '', shortName: '', aliases: [] }, values || {});
  }

  function hasContent(mapping) {
    return Boolean(mapping.pairing.trim() || mapping.shortName.trim() || mapping.aliases.some(function (alias) { return alias.trim(); }));
  }

  function cleanMappings() {
    return mappings.filter(hasContent).map(function (mapping) {
      return {
        pairing: mapping.pairing.trim(),
        shortName: mapping.shortName.trim(),
        aliases: unique(mapping.aliases.map(function (alias) { return alias.trim(); }).filter(Boolean))
      };
    });
  }

  function renderMappings() {
    elements.mappingList.innerHTML = '';
    mappings.forEach(function (mapping, index) {
      const card = document.createElement('fieldset');
      card.className = 'mapping-card';
      card.dataset.id = String(mapping.id);

      const legend = document.createElement('legend');
      legend.textContent = 'Ship ' + (index + 1);
      card.appendChild(legend);

      const fields = document.createElement('div');
      fields.className = 'mapping-fields';
      fields.appendChild(makeInput('AO3 relationship', 'pairing', mapping.pairing, 'Sherlock Holmes/John Watson'));
      fields.appendChild(makeInput('Short name', 'shortName', mapping.shortName, 'Johnlock'));
      card.appendChild(fields);

      const aliasLabel = document.createElement('label');
      aliasLabel.textContent = 'Alternative names (optional, one per line)';
      const aliasArea = document.createElement('textarea');
      aliasArea.rows = 2;
      aliasArea.name = 'aliases';
      aliasArea.value = mapping.aliases.join('\n');
      aliasArea.placeholder = 'John/Sherlock\nSherlock/John';
      aliasLabel.appendChild(aliasArea);
      card.appendChild(aliasLabel);

      const actions = document.createElement('div');
      actions.className = 'mapping-actions';
      const orderActions = document.createElement('div');
      orderActions.className = 'mapping-action-group';
      orderActions.appendChild(actionButton('Move up', 'up', index === 0));
      orderActions.appendChild(actionButton('Move down', 'down', index === mappings.length - 1));
      const editActions = document.createElement('div');
      editActions.className = 'mapping-action-group';
      editActions.appendChild(actionButton('Duplicate', 'duplicate', false));
      editActions.appendChild(actionButton('Delete', 'delete', mappings.length === 1));
      actions.appendChild(orderActions);
      actions.appendChild(editActions);
      card.appendChild(actions);

      card.addEventListener('input', function () {
        syncMappingCard(card);
        changed();
      });
      card.addEventListener('click', handleMappingAction);
      elements.mappingList.appendChild(card);
    });
  }

  function makeInput(labelText, name, value, placeholder) {
    const label = document.createElement('label');
    label.textContent = labelText;
    const input = document.createElement('input');
    input.type = 'text';
    input.name = name;
    input.value = value;
    input.placeholder = placeholder;
    label.appendChild(input);
    return label;
  }

  function actionButton(text, action, disabled) {
    const button = document.createElement('button');
    button.type = 'button';
    button.className = 'mapping-action';
    button.dataset.action = action;
    button.textContent = text;
    button.disabled = disabled;
    return button;
  }

  function handleMappingAction(event) {
    const button = event.target.closest('button[data-action]');
    if (!button) return;
    syncMappingsFromForm();
    const card = button.closest('.mapping-card');
    const id = Number(card.dataset.id);
    const index = mappings.findIndex(function (mapping) { return mapping.id === id; });
    if (index < 0) return;

    if (button.dataset.action === 'up' && index > 0) {
      const item = mappings.splice(index, 1)[0];
      mappings.splice(index - 1, 0, item);
    } else if (button.dataset.action === 'down' && index < mappings.length - 1) {
      const item = mappings.splice(index, 1)[0];
      mappings.splice(index + 1, 0, item);
    } else if (button.dataset.action === 'duplicate') {
      const copy = newMapping({
        pairing: mappings[index].pairing,
        shortName: mappings[index].shortName,
        aliases: mappings[index].aliases.slice()
      });
      mappings.splice(index + 1, 0, copy);
    } else if (button.dataset.action === 'delete' && mappings.length > 1) {
      mappings.splice(index, 1);
    }

    renderMappings();
    changed();
  }

  function syncMappingCard(card) {
    const mapping = mappings.find(function (item) { return item.id === Number(card.dataset.id); });
    if (!mapping) return;
    mapping.pairing = card.querySelector('[name="pairing"]').value;
    mapping.shortName = card.querySelector('[name="shortName"]').value;
    mapping.aliases = card.querySelector('[name="aliases"]').value.split(/\r?\n/);
  }

  function syncMappingsFromForm() {
    elements.mappingList.querySelectorAll('.mapping-card').forEach(syncMappingCard);
  }

  function focusMapping(id) {
    const input = elements.mappingList.querySelector('[data-id="' + id + '"] [name="pairing"]');
    if (input) input.focus();
  }

  function changed() {
    syncMappingsFromForm();
    saveDraft();
    updatePreview();
    showValidation(validateMappings());
    if (!elements.outputWrap.hidden) {
      elements.copyTemplate.disabled = true;
      elements.downloadTemplate.disabled = true;
      showMessage(elements.copyMessage, 'Your rows changed. Generate the template again before copying it.', 'info');
    }
  }

  function syncCategoryControls() {
    const enabled = elements.categoryFallback.checked;
    elements.categoryFallbackSettings.hidden = !enabled;
    elements.previewCategoryWrap.hidden = !enabled;
    elements.categoryColumn.disabled = !enabled;
    elements.previewCategory.disabled = !enabled;
  }

  function validateMappings() {
    const errors = [];
    const warnings = [];
    const seenRelationships = new Map();

    mappings.forEach(function (mapping, index) {
      if (!hasContent(mapping)) return;
      const number = index + 1;
      if (!mapping.pairing.trim()) errors.push('Ship ' + number + ' needs an AO3 relationship.');
      if (!mapping.shortName.trim()) errors.push('Ship ' + number + ' needs a short name.');
      if (mapping.pairing.trim() && !mapping.pairing.includes('/')) errors.push('Ship ' + number + ' needs a relationship containing /.');
      if (mapping.pairing.includes(',')) errors.push('Ship ' + number + ' contains a comma. Calibre uses commas to separate relationships, so this name cannot be generated safely.');
      if (mapping.shortName.includes(',')) errors.push('Ship ' + number + ' has a comma in its short name. Choose a short name without a comma.');
      if (mapping.shortName.includes("'") && mapping.shortName.includes('"')) {
        errors.push('Ship ' + number + ' has both kinds of quotation marks in its short name. Please simplify that short name.');
      }

      mapping.aliases.map(function (alias) { return alias.trim(); }).filter(Boolean).forEach(function (alias) {
        if (!alias.includes('/')) errors.push('The alternative name “' + alias + '” in ship ' + number + ' does not contain /.');
        if (alias.includes(',')) errors.push('The alternative name “' + alias + '” contains a comma and cannot be generated safely.');
      });

      [mapping.pairing].concat(mapping.aliases).map(function (value) { return value.trim(); }).filter(Boolean).forEach(function (relationship) {
        const key = relationship.toLocaleLowerCase();
        if (seenRelationships.has(key) && seenRelationships.get(key) !== mapping.shortName.trim().toLocaleLowerCase()) {
          errors.push('“' + relationship + '” is assigned to more than one short name.');
        } else if (seenRelationships.has(key)) {
          warnings.push('“' + relationship + '” appears more than once. The duplicate can be removed.');
        } else {
          seenRelationships.set(key, mapping.shortName.trim().toLocaleLowerCase());
        }
      });
    });

    if (!cleanMappings().length) errors.push('Add at least one ship before generating the template.');
    if (elements.categoryFallback.checked && !isValidLookupName(elements.categoryColumn.value)) {
      errors.push('Enter a valid category column lookup name, such as #ao3_category or relationship_type.');
    }
    return { errors: unique(errors), warnings: unique(warnings) };
  }

  function showValidation(validation) {
    const messages = validation.errors.concat(validation.warnings);
    if (!messages.length) {
      elements.validationMessage.hidden = true;
      elements.validationMessage.innerHTML = '';
      return;
    }
    elements.validationMessage.className = 'generator-message generator-warning-list ' + (validation.errors.length ? 'is-error' : 'is-warning');
    elements.validationMessage.innerHTML = '<strong>' + (validation.errors.length ? 'Please fix:' : 'Worth checking:') + '</strong><ul>' + messages.map(function (message) {
      return '<li>' + escapeHtml(message) + '</li>';
    }).join('') + '</ul>';
    elements.validationMessage.hidden = false;
  }

  function updatePreview() {
    syncMappingsFromForm();
    elements.previewOutput.textContent = previewValue(
      elements.previewInput.value,
      cleanMappings(),
      Number(elements.shipLimit.value) || DEFAULT_LIMIT,
      {
        categoryFallback: elements.categoryFallback.checked,
        categoryValue: elements.previewCategory.value
      }
    );
  }

  function previewValue(input, usableMappings, limit, options) {
    const settings = options || {};
    const relationships = unique(input.split(',').map(function (item) { return item.trim(); }).filter(function (item) { return item.includes('/'); }), true).slice(0, limit);
    const output = [];

    relationships.forEach(function (relationship) {
      const key = relationship.toLocaleLowerCase();
      const mapping = usableMappings.find(function (item) {
        return [item.pairing].concat(item.aliases).some(function (name) { return name.toLocaleLowerCase() === key; });
      });
      const shortName = mapping ? mapping.shortName : relationship;
      if (!output.some(function (name) { return name.toLocaleLowerCase() === shortName.toLocaleLowerCase(); })) output.push(shortName);
    });

    if (output.length) return output.join(', ');
    if (settings.categoryFallback) {
      const category = ao3Categories(settings.categoryValue || '');
      if (category) return category;
    }
    return 'Gen';
  }

  function importTemplate() {
    const source = elements.importCode.value.trim();
    if (!source) {
      showMessage(elements.importMessage, 'Paste a template first.', 'error');
      return;
    }
    if (!source.includes('program:') || !source.includes("field('#all_slashes')")) {
      showMessage(elements.importMessage, 'This does not look like the tutorial #all_slashes template.', 'error');
      return;
    }

    const imported = parseTemplate(source);
    if (!imported.mappings.length) {
      showMessage(elements.importMessage, 'I found the template, but could not recognise any ship-name rules. No rows were replaced.', 'error');
      return;
    }
    if (mappings.some(hasContent) && !window.confirm('Replace your current rows with the ships found in this code?')) return;

    mappings = imported.mappings.map(function (item) { return newMapping(item); });
    elements.shipLimit.value = String(imported.limit);
    elements.categoryFallback.checked = imported.categoryFallback;
    elements.categoryColumn.value = imported.categoryColumn;
    syncCategoryControls();
    renderMappings();
    changed();
    showMessage(elements.importMessage, 'Imported ' + mappings.length + ' ship ' + (mappings.length === 1 ? 'row' : 'rows') + ', a ' + imported.limit + '-ship display limit' + (imported.categoryFallback ? ', and the category fallback.' : '.'), 'success');
  }

  function parseTemplate(source) {
    const slotMatches = Array.from(source.matchAll(/s(\d+)\s*=\s*re\(list_item\(ordered_unique,\s*(\d+)/g));
    const limitComment = source.match(/# Shows up to\s+(\d+)\s+different\s+ships?/i);
    let limit = limitComment ? Number(limitComment[1]) : (slotMatches.length ? Math.max.apply(null, slotMatches.map(function (match) { return Number(match[2]); })) + 1 : DEFAULT_LIMIT);
    limit = Math.min(6, Math.max(1, limit));

    const rulePattern = /(?:if|elif)\s+contains\(\s*(?:s\d+_(?:lc|value)|ship_value),\s*(['"])(.*?)\1,\s*['"]1['"],\s*['"]{2}\s*\)(?:\s*\|\|[^\n]+)?\s*then\s*(?:t\d+|translated)\s*=\s*(['"])(.*?)\3/g;
    const grouped = new Map();
    let match;
    while ((match = rulePattern.exec(source)) !== null) {
      const shortName = match[4];
      const names = splitPattern(match[2]);
      if (!names.length) continue;
      const key = shortName.toLocaleLowerCase();
      if (!grouped.has(key)) grouped.set(key, { pairing: names[0], shortName: shortName, aliases: names.slice(1) });
      else {
        const row = grouped.get(key);
        row.aliases = unique(row.aliases.concat(names).filter(function (name) { return name.toLocaleLowerCase() !== row.pairing.toLocaleLowerCase(); }), true);
      }
    }
    const categoryMarker = source.match(/^# Category fallback column:\s*(#?[A-Za-z][A-Za-z0-9_]*)\s*$/m);
    const categoryCode = source.match(/list_intersection\([\s\S]*?field\(\s*(['"])(#?[A-Za-z][A-Za-z0-9_]*)\1\s*\)[\s\S]*?\)/);
    const categoryColumn = categoryMarker ? categoryMarker[1] : (categoryCode ? categoryCode[2] : '#ao3_category');
    return {
      mappings: Array.from(grouped.values()),
      limit: limit,
      categoryFallback: Boolean(categoryMarker || categoryCode),
      categoryColumn: normalizeLookupName(categoryColumn)
    };
  }

  function splitPattern(pattern) {
    let value = pattern.replace(/^\(\?i\)/, '').replace(/^\^\(\?:/, '').replace(/\)\$$/, '');
    const parts = [];
    let current = '';
    let escaped = false;
    for (const character of value) {
      if (escaped) {
        current += '\\' + character;
        escaped = false;
      } else if (character === '\\') {
        escaped = true;
      } else if (character === '|') {
        parts.push(current);
        current = '';
      } else {
        current += character;
      }
    }
    if (escaped) current += '\\';
    parts.push(current);
    return parts.map(unescapeGeneratedPattern).filter(Boolean);
  }

  function unescapeGeneratedPattern(value) {
    return value.replace(/\\x27/gi, "'").replace(/\\([\\^$.*+?()[\]{}|])/g, '$1');
  }

  function generateTemplate(rows, limit, options) {
    const settings = options || {};
    const categoryColumn = normalizeLookupName(settings.categoryColumn || '#ao3_category');
    const lines = [
      'program:',
      GENERATOR_MARKER,
      '# Shows up to ' + limit + ' different ' + (limit === 1 ? 'ship' : 'ships') + ' from #all_slashes.',
      '',
      '# Read the saved ship list, remove repeats, and take the requested number.',
      "ordered_unique = list_remove_duplicates(field('#all_slashes'), ',');",
      "selected = sublist(ordered_unique, 0, " + limit + ", ',');",
      "result = '';",
      '',
      '# If this is an older fic with no #all_slashes value, try #ship instead.',
      'if !selected then',
      "    ships_raw = field('#ship');",
      "    if contains(ships_raw, '/', '1', '') then",
      "        fallback = re(ships_raw, '^(?:[^/,]+,\\s*)*([^,]+/[^,]+)(?:,.*)?$', '\\1');",
      "        if contains(fallback, '/', '1', '') && !contains(fallback, ',', '1', '') then",
      '            selected = fallback',
      '        fi',
      '    fi',
      'fi;',
      '',
      '# Translate each selected relationship.',
      "for ship in selected separator ',':",
      "    ship_value = re(ship, '^\\s+|\\s+$', '');",
      "    translated = '';"
    ];

    rows.forEach(function (row, rowIndex) {
      const names = unique([row.pairing].concat(row.aliases), true);
      const keyword = rowIndex === 0 ? 'if' : 'elif';
      lines.push('    ' + keyword + " contains(ship_value, '(?i)^(?:" + names.map(regexEscape).join('|') + ")$', '1', '') then");
      lines.push('        translated = ' + quoteTemplateString(row.shortName));
    });
    lines.push(
      '    else',
      "        translated = re(ship_value, '(?i)([^/]+)/([^/]+)', '\\1/\\2')",
      '    fi;',
      "    if translated then result = list_join(', ', result, ',', translated, ',') fi",
      'rof;'
    );
    if (settings.categoryFallback) {
      lines.push(
        '',
        '# If no relationship was found, use known AO3 relationship categories.',
        '# Category fallback column: ' + categoryColumn,
        'if !result then',
        '    result = list_intersection(',
        "        'Gen, F/F, F/M, M/M, Multi, Other',",
        "        field('" + categoryColumn + "'),",
        "        ','",
        '    )',
        'fi;'
      );
    }
    lines.push('', "if !result then return 'Gen' else return result fi");
    return lines.join('\n');
  }

  function regexEscape(value) {
    return value.trim().replace(/[\\^$.*+?()[\]{}|]/g, '\\$&').replace(/'/g, '\\x27');
  }

  function ao3Categories(value) {
    const available = value.split(',').map(function (item) { return item.trim(); });
    return ['Gen', 'F/F', 'F/M', 'M/M', 'Multi', 'Other'].filter(function (category) {
      return available.includes(category);
    }).join(', ');
  }

  function isValidLookupName(value) {
    return /^#?[A-Za-z][A-Za-z0-9_]*$/.test(String(value || '').trim());
  }

  function normalizeLookupName(value) {
    const name = String(value || '').trim();
    return name.startsWith('#') ? name : '#' + name;
  }

  function quoteTemplateString(value) {
    if (!value.includes("'")) return "'" + value + "'";
    if (!value.includes('"')) return '"' + value + '"';
    throw new Error('Text containing both kinds of quotation marks is not supported.');
  }

  function unique(items, caseInsensitive) {
    const seen = new Set();
    return items.filter(function (item) {
      const key = caseInsensitive ? item.toLocaleLowerCase() : item;
      if (seen.has(key)) return false;
      seen.add(key);
      return true;
    });
  }

  function saveDraft() {
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify({
        mappings: mappings,
        limit: Number(elements.shipLimit.value),
        categoryFallback: elements.categoryFallback.checked,
        categoryColumn: elements.categoryColumn.value
      }));
    } catch (error) {
      // The generator still works when browser storage is unavailable.
    }
  }

  function loadDraft() {
    try {
      const draft = JSON.parse(localStorage.getItem(STORAGE_KEY));
      if (!draft || !Array.isArray(draft.mappings)) return { mappings: [], categoryFallback: false, categoryColumn: '#ao3_category' };
      if (draft.limit >= 1 && draft.limit <= 6) elements.shipLimit.value = String(draft.limit);
      return {
        mappings: draft.mappings.map(function (item) {
          return {
            id: Number(item.id) || 0,
            pairing: String(item.pairing || ''),
            shortName: String(item.shortName || ''),
            aliases: Array.isArray(item.aliases) ? item.aliases.map(String) : []
          };
        }),
        categoryFallback: Boolean(draft.categoryFallback),
        categoryColumn: isValidLookupName(draft.categoryColumn) ? String(draft.categoryColumn) : '#ao3_category'
      };
    } catch (error) {
      return { mappings: [], categoryFallback: false, categoryColumn: '#ao3_category' };
    }
  }

  function showMessage(element, text, type) {
    if (!text) {
      element.hidden = true;
      element.textContent = '';
      return;
    }
    element.className = 'generator-message is-' + type;
    element.textContent = text;
    element.hidden = false;
  }

  function escapeHtml(value) {
    return value.replace(/[&<>"']/g, function (character) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#039;' }[character];
    });
  }
})();
