(function () {
  'use strict';

  const STORAGE_KEY = 'fff-covers-genre-generator-v1';
  const MARKER = '# Generated by the fff-covers genre generator v1';
  window.FFFGenreGeneratorCore = { generateTemplate, parseTemplate, previewValue, regexEscape };

  const root = document.getElementById('genre-generator');
  if (!root) return;

  const examples = [
    { label: 'Fluff', keywords: ['fluff', 'domestic', 'domestic bliss', 'soft', 'slice of life', 'comfort'] },
    { label: 'Whump', keywords: ['hurt/comfort', 'whump', 'hurt', 'sick', 'illness', 'injury', 'recovery'] },
    { label: 'Angst', keywords: ['angst', 'major character death', 'grief', 'ptsd', 'trauma', 'depression'] },
    { label: 'ABO', keywords: ['alpha/beta/omega', 'omegaverse', 'abo'] }
  ];
  const el = {};
  ['mapping-list', 'source-field', 'add-mapping', 'clear-mappings', 'load-examples', 'import-code', 'import-template', 'clear-import', 'import-message', 'validation-message', 'preview-input', 'preview-output', 'generate-template', 'output-wrap', 'generated-code', 'copy-template', 'download-template', 'copy-message'].forEach(function (name) {
    el[toCamel(name)] = document.getElementById('genre-' + name);
  });

  let state = loadDraft();
  let nextId = state.rows.reduce(function (n, row) { return Math.max(n, row.id || 0); }, 0) + 1;
  let rows = state.rows.length ? state.rows : [newRow()];
  el.sourceField.value = state.source || 'tags';
  render(); updatePreview();

  el.addMapping.addEventListener('click', function () { rows.push(newRow()); render(); changed(); });
  el.clearMappings.addEventListener('click', function () {
    if (rows.some(hasContent) && !window.confirm('Clear every genre row?')) return;
    rows = [newRow()]; render(); changed();
  });
  el.loadExamples.addEventListener('click', function () {
    if (rows.some(hasContent) && !window.confirm('Replace your current rows with the tutorial examples?')) return;
    rows = examples.map(function (row) { return newRow(row); });
    el.sourceField.value = 'tags';
    el.previewInput.value = 'Fluff, Domestic Bliss, Friends to Lovers, Angst';
    render(); changed();
  });
  el.sourceField.addEventListener('input', changed);
  el.previewInput.addEventListener('input', updatePreview);
  el.clearImport.addEventListener('click', function () { el.importCode.value = ''; message(el.importMessage, '', 'info'); });
  el.importTemplate.addEventListener('click', function () {
    try {
      const imported = parseTemplate(el.importCode.value);
      rows = imported.rows.map(function (row) { return newRow(row); });
      el.sourceField.value = imported.source;
      render(); changed(); message(el.importMessage, 'Imported ' + rows.length + ' genre rows.', 'success');
    } catch (error) { message(el.importMessage, error.message, 'error'); }
  });
  el.generateTemplate.addEventListener('click', function () {
    sync();
    const errors = validate();
    showErrors(errors);
    if (errors.length) return;
    el.generatedCode.value = generateTemplate(cleanRows(), el.sourceField.value.trim());
    el.outputWrap.hidden = false; el.copyTemplate.disabled = false; el.downloadTemplate.disabled = false;
    message(el.copyMessage, 'Template generated. Copy it into your #genre column.', 'success'); saveDraft();
  });
  el.copyTemplate.addEventListener('click', async function () {
    try { await navigator.clipboard.writeText(el.generatedCode.value); message(el.copyMessage, 'Copied. You can now paste the template into Calibre.', 'success'); }
    catch (error) { el.generatedCode.focus(); el.generatedCode.select(); message(el.copyMessage, 'Automatic copying was blocked. The code is selected; use your normal copy command.', 'error'); }
  });
  el.downloadTemplate.addEventListener('click', function () {
    const url = URL.createObjectURL(new Blob([el.generatedCode.value], { type: 'text/plain;charset=utf-8' }));
    const link = document.createElement('a'); link.href = url; link.download = 'genre.txt'; document.body.appendChild(link); link.click(); link.remove(); URL.revokeObjectURL(url);
  });

  function newRow(values) { return Object.assign({ id: nextId++, label: '', keywords: [] }, values || {}); }
  function hasContent(row) { return Boolean(row.label.trim() || row.keywords.some(function (item) { return item.trim(); })); }
  function cleanRows() { return rows.filter(hasContent).map(function (row) { return { label: row.label.trim(), keywords: unique(row.keywords.map(function (x) { return x.trim(); }).filter(Boolean), true) }; }); }
  function render() {
    el.mappingList.innerHTML = '';
    rows.forEach(function (row, index) {
      const card = document.createElement('fieldset'); card.className = 'mapping-card'; card.dataset.id = row.id;
      const legend = document.createElement('legend'); legend.textContent = 'Genre ' + (index + 1); card.appendChild(legend);
      const fields = document.createElement('div'); fields.className = 'mapping-fields genre-mapping-fields';
      fields.appendChild(input('Genre shown on the cover', 'label', row.label, 'Fluff'));
      const keywordLabel = document.createElement('label'); keywordLabel.textContent = 'Matching keyphrases (one per line)';
      const area = document.createElement('textarea'); area.name = 'keywords'; area.rows = 5; area.value = row.keywords.join('\n'); area.placeholder = 'fluff\ndomestic bliss\nslice of life'; keywordLabel.appendChild(area); fields.appendChild(keywordLabel); card.appendChild(fields);
      const actions = document.createElement('div'); actions.className = 'mapping-actions';
      const left = document.createElement('div'); left.className = 'mapping-action-group'; left.appendChild(button('Move up', 'up', index === 0)); left.appendChild(button('Move down', 'down', index === rows.length - 1));
      const right = document.createElement('div'); right.className = 'mapping-action-group'; right.appendChild(button('Duplicate', 'duplicate')); right.appendChild(button('Delete', 'delete', rows.length === 1)); actions.appendChild(left); actions.appendChild(right); card.appendChild(actions);
      card.addEventListener('input', function () { syncCard(card); changed(); }); card.addEventListener('click', handleAction); el.mappingList.appendChild(card);
    });
  }
  function input(text, name, value, placeholder) { const label = document.createElement('label'); label.textContent = text; const field = document.createElement('input'); field.name = name; field.value = value; field.placeholder = placeholder; label.appendChild(field); return label; }
  function button(text, action, disabled) { const b = document.createElement('button'); b.type = 'button'; b.className = 'mapping-action'; b.dataset.action = action; b.textContent = text; b.disabled = Boolean(disabled); return b; }
  function handleAction(event) {
    const action = event.target.dataset.action; if (!action) return;
    sync(); const id = Number(event.currentTarget.dataset.id); const index = rows.findIndex(function (row) { return row.id === id; });
    if (action === 'up' && index > 0) rows.splice(index - 1, 0, rows.splice(index, 1)[0]);
    if (action === 'down' && index < rows.length - 1) rows.splice(index + 1, 0, rows.splice(index, 1)[0]);
    if (action === 'duplicate') rows.splice(index + 1, 0, newRow({ label: rows[index].label, keywords: rows[index].keywords.slice() }));
    if (action === 'delete' && rows.length > 1) rows.splice(index, 1);
    render(); changed();
  }
  function syncCard(card) { const row = rows.find(function (item) { return item.id === Number(card.dataset.id); }); row.label = card.querySelector('[name=label]').value; row.keywords = card.querySelector('[name=keywords]').value.split(/\r?\n/); }
  function sync() { Array.prototype.forEach.call(el.mappingList.querySelectorAll('.mapping-card'), syncCard); }
  function changed() { sync(); updatePreview(); saveDraft(); el.outputWrap.hidden = true; }
  function updatePreview() { sync(); el.previewOutput.textContent = previewValue(el.previewInput.value, cleanRows()) || 'No matches'; }
  function validate() {
    const errors = [], cleaned = cleanRows(), labels = new Set();
    if (!/^#?[A-Za-z][A-Za-z0-9_]*$/.test(el.sourceField.value.trim())) errors.push('Enter a valid Calibre lookup name, such as tags or #ao3_tags.');
    if (!cleaned.length) errors.push('Add at least one genre.');
    cleaned.forEach(function (row, i) { const n = i + 1; if (!row.label) errors.push('Genre ' + n + ' needs a cover label.'); if (!row.keywords.length) errors.push('Genre ' + n + ' needs at least one keyphrase.'); if (row.keywords.some(function (x) { return x.includes(','); })) errors.push('Genre ' + n + ' has a comma in a keyphrase. Use the text on either side as separate keyphrases.'); if ([row.label].concat(row.keywords).some(function (x) { return x.includes("'") && x.includes('"'); })) errors.push('Genre ' + n + ' contains both single and double quotation marks, which this generator cannot safely add to Calibre code.'); const key = row.label.toLowerCase(); if (labels.has(key)) errors.push('The cover label “' + row.label + '” is used more than once.'); labels.add(key); });
    return unique(errors);
  }
  function showErrors(errors) { if (!errors.length) return message(el.validationMessage, '', 'info'); el.validationMessage.innerHTML = '<strong>Please fix:</strong><ul>' + errors.map(function (x) { return '<li>' + escapeHtml(x) + '</li>'; }).join('') + '</ul>'; el.validationMessage.className = 'generator-message generator-warning-list is-error'; el.validationMessage.hidden = false; }
  function saveDraft() { try { localStorage.setItem(STORAGE_KEY, JSON.stringify({ source: el.sourceField.value, rows: rows })); } catch (error) {} }
  function loadDraft() { try { const data = JSON.parse(localStorage.getItem(STORAGE_KEY)); return data && Array.isArray(data.rows) ? data : { source: 'tags', rows: [] }; } catch (error) { return { source: 'tags', rows: [] }; } }
  function message(node, text, type) { node.hidden = !text; node.textContent = text; node.className = 'generator-message is-' + type; }
  function toCamel(value) { return value.replace(/-([a-z])/g, function (_, c) { return c.toUpperCase(); }); }
  function escapeHtml(value) { return value.replace(/[&<>"']/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#039;' }[c]; }); }

  function generateTemplate(inputRows, source) {
    const lines = [MARKER, '# Reads tags from ' + source + ' and keeps the genre order shown here.', 'program:', "tags = lowercase(field(" + quote(source) + "));", "result = '';", ''];
    inputRows.forEach(function (row) {
      const pattern = row.keywords.map(function (word) { return regexEscape(word.toLowerCase()); }).join('|');
      lines.push('# Genre: ' + quote(row.label), '# Keyphrases: ' + quote(row.keywords.join('|')), "if contains(tags, '(?:" + pattern + ")', '1', '') then", "    result = list_join(', ', result, ',', " + quote(row.label) + ", ',')", 'fi;', '');
    });
    lines.push('return result'); return lines.join('\n');
  }
  function parseTemplate(code) {
    if (!code || code.indexOf('program:') < 0) throw new Error('Paste the complete genre template, beginning with program:.');
    const sourceMatch = code.match(/field\((['"])(#?[A-Za-z][A-Za-z0-9_]*)\1\)/); const source = sourceMatch ? sourceMatch[2] : 'tags';
    const parsed = []; let match;
    const metadata = /# Genre: (['"])(.*?)\1\s*\n# (?:Keyphrases|Keywords): (['"])(.*?)\3/g;
    while ((match = metadata.exec(code))) parsed.push({ label: match[2], keywords: match[4].split('|').filter(Boolean) });
    if (!parsed.length) {
      const tutorial = /contains\(tags,\s*(['"])([\s\S]*?)\1,\s*'1',\s*''\),\s*(['"])(.*?)\3,\s*''\)/g;
      while ((match = tutorial.exec(code))) parsed.push({ label: match[4], keywords: match[2].replace(/\s+/g, ' ').trim().split('|').filter(Boolean) });
    }
    if (!parsed.length) throw new Error('No tutorial-style genre rows were found in that code.');
    return { source: source, rows: parsed };
  }
  function previewValue(tags, inputRows) { const haystack = tags.toLowerCase(), result = []; inputRows.forEach(function (row) { if (row.keywords.some(function (word) { return haystack.includes(word.toLowerCase()); }) && !result.includes(row.label)) result.push(row.label); }); return result.join(', '); }
  function regexEscape(value) { return value.trim().replace(/[\\^$.*+?()[\]{}|]/g, '\\$&').replace(/'/g, '\\x27'); }
  function quote(value) { if (!value.includes("'")) return "'" + value + "'"; if (!value.includes('"')) return '"' + value + '"'; throw new Error('Text containing both kinds of quotation marks is not supported.'); }
  function unique(items, insensitive) { const seen = new Set(); return items.filter(function (item) { const key = insensitive ? item.toLowerCase() : item; if (seen.has(key)) return false; seen.add(key); return true; }); }
})();
